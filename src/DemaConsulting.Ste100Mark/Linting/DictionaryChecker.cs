using System.Collections.Frozen;
using System.Text.RegularExpressions;

namespace DemaConsulting.Ste100Mark.Linting;

/// <summary>
///     Scans prose text for disallowed vocabulary from a merged <see cref="LintDictionary"/> and
///     reports the matched term with its suggested alternative(s), using
///     <see cref="IPartOfSpeechResolver"/> to select the applicable sense(s) when a term has more
///     than one.
/// </summary>
/// <remarks>
///     The dictionary check is a mechanical, non-advisory rule: any match is reported at
///     <see cref="Severity.Error"/>, with rule code <c>STE100-DICT</c>. Matching is case-insensitive
///     and whole-word/whole-phrase (a match cannot start or end mid-word or inside a hyphenated
///     compound). Multi-word terms match across the segment's normalized single-space-separated text.
///
///     By default (<see cref="DictionaryConfig.MatchWordForms"/>) a term is also matched in its
///     inflected forms, generated by <see cref="WordFormInflector"/>: the third-person, past,
///     past participle and -ing forms of each verb sense (the first word of a phrasal verb), and
///     the plural of each noun sense, so "utilized" is flagged by a "utilize" verb entry. Adjective,
///     adverb and any-role senses are never inflected. A generated form is strictly role-gated:
///     it only applies to the noun or verb sense that generated it, so a noun-only entry's plural
///     is not flagged where the resolver says the word is a verb. The participial forms (-ed, -ing
///     and irregular past or past participle) are flagged only when the resolver confidently
///     resolves a verb (a phrasal verb is resolved on its head word); an ambiguous or inconclusive
///     result, or a confident noun or adjective, is not flagged. The base form and the
///     third-person and plural forms keep reporting when the role is inconclusive. A generated spelling never
///     overrides an explicit dictionary entry for that spelling, an allowed or ignored spelling
///     (global lists or the per-file allowance), or an allowed phrase. The message names the
///     flagged form ("a form of 'utilize'") and the suggested alternatives are inflected to match
///     when that is safe; otherwise the base alternative is shown and the message says so.
///     Citations always keep the dictionary's base-form alternatives.
///
///     All patterns (one alternation per entry plus one per allowed phrase) are compiled once per
///     <see cref="Evaluate"/> call rather than once per segment.
///
///     A term is always evaluated through <see cref="IPartOfSpeechResolver.Resolve"/>, even when it
///     has only one sense: when the resolver confidently resolves a grammatical role (noun, verb,
///     adjective, adverb, or resolver-only determiner) that none of the entry's senses restrict, the term is not being used in a
///     disallowed role at this location and no diagnostic is reported. When the resolved role matches
///     one sense, that sense's alternative(s) are reported (labeled with the resolved part of
///     speech only when the entry has more than one sense, so a single-sense entry's message
///     stays unqualified). When the resolution is inconclusive (or the entry has multiple senses
///     none of which the resolved role narrows to exactly one), every remaining candidate sense is reported,
///     labeled as ambiguous.
///
///     A match that falls entirely inside an inline code span (for example, a disallowed term that
///     only appears as part of `` `some-cli-flag` ``) is ignored: inline code spans are technical
///     literals, not grammar-checkable prose, so they are excluded from the dictionary check the
///     same way they are excluded from the contraction and semicolon checks in
///     <see cref="StructuralRules"/>. The same term appearing outside a code span in the same
///     segment is still flagged normally.
///
///     A match that falls entirely inside an occurrence of a project-supplied allowed phrase (see
///     <see cref="DictionaryConfig.AllowInPhrase"/>, resolved per-file into
///     <c>allowedPhrases</c>) is also ignored, using the same "falls entirely inside" containment
///     test as the inline-code-span exclusion. This lets a project declare that a specific phrase
///     (for example "trail mix") is the approved name of a thing, without also silently permitting
///     the disallowed word ("mix") everywhere else it appears - unlike
///     <see cref="LintConfig.ResolveAllowedTerms"/>, which suppresses a term unconditionally.
/// </remarks>
internal static class DictionaryChecker
{
    /// <summary>
    ///     Scans every prose segment of a Markdown file against the merged dictionary.
    /// </summary>
    /// <param name="file">File path used to populate <see cref="Diagnostic.File"/>.</param>
    /// <param name="segments">Prose segments produced by <see cref="MarkdownProseExtractor"/>.</param>
    /// <param name="dictionary">Merged dictionary to check against.</param>
    /// <param name="extraAllowedTerms">
    ///     Additional terms to treat as allowed for this file only, on top of
    ///     <paramref name="dictionary"/>'s own global allow/ignore lists - typically the file's
    ///     resolved <see cref="LintConfig.ResolveAllowedTerms"/> profile deltas (for example,
    ///     permitting "shall" only for a requirements-documents profile). Pass <see langword="null"/>
    ///     or an empty collection when no per-file allowance applies.
    /// </param>
    /// <param name="allowedPhrases">
    ///     Phrases (see <see cref="DictionaryConfig.AllowInPhrase"/>, resolved per-file
    ///     via <see cref="LintConfig.ResolveAllowedPhrases"/>) within which a disallowed term match
    ///     is suppressed, without suppressing the same term elsewhere in the segment. Pass
    ///     <see langword="null"/> or an empty collection when no phrase-scoped allowance applies.
    /// </param>
    /// <param name="resolver">
    ///     The part-of-speech resolver to use; <see langword="null"/> selects the process-wide default
    ///     <see cref="PartOfSpeechResolver"/> (supplied explicitly only by tests).
    /// </param>
    /// <param name="collectDetail">
    ///     When <see langword="true"/>, each diagnostic carries a <see cref="DictionaryEvidence"/>
    ///     record (see <see cref="Diagnostic.Evidence"/>) for the detailed JSON output; the
    ///     message, suggestion, citations, line and column are identical either way.
    /// </param>
    /// <returns>One diagnostic per matched occurrence, in segment order.</returns>
    public static IReadOnlyList<Diagnostic> Evaluate(
        string file,
        IReadOnlyList<ProseSegment> segments,
        LintDictionary dictionary,
        IReadOnlyCollection<string>? extraAllowedTerms = null,
        IReadOnlyCollection<string>? allowedPhrases = null,
        IPartOfSpeechResolver? resolver = null,
        bool collectDetail = false)
    {
        ArgumentNullException.ThrowIfNull(file);
        ArgumentNullException.ThrowIfNull(segments);
        ArgumentNullException.ThrowIfNull(dictionary);
        resolver ??= PartOfSpeechResolver.Shared;

        var allowedTerms = extraAllowedTerms is { Count: > 0 }
            ? new HashSet<string>(extraAllowedTerms, StringComparer.OrdinalIgnoreCase)
            : null;

        // Longer (more specific) terms are matched first so that a multi-word phrase like
        // "prior to" is reported once, rather than also triggering a shorter, unrelated
        // single-word entry that happens to overlap.
        var entries = dictionary.Entries
            .Where(e => allowedTerms is null || !allowedTerms.Contains(e.Term))
            .OrderByDescending(e => e.Term.Length)
            .ToList();

        // Build every pattern once per call (not once per segment): one alternation per entry
        // covering the base term and, when enabled, its generated word forms.
        var compiledEntries = CompileEntries(entries, dictionary, allowedTerms);
        var phrasePatterns = CompilePhrasePatterns(allowedPhrases);

        var diagnostics = new List<Diagnostic>();
        foreach (var segment in segments)
        {
            if (segment.Role == SegmentRole.TableHeader)
            {
                // Table column header cells (for example "Hazard", "Use") are short labels, not
                // prose sentences, and are routinely a bare noun/verb-looking word out of any
                // sentence context - they are excluded from the dictionary check entirely, the
                // same way headings and table headers are excluded from the -ing-form advisory
                // (see StructuralRules.EvaluateIngForm).
                continue;
            }

            var codeSpans = MarkdownProseExtractor.FindInlineCodeSpans(segment.Text);
            var phraseSpans = FindAllowedPhraseSpans(segment.Text, phrasePatterns);
            var admonitionSpans = MarkdownProseExtractor.FindAdmonitionLabelSpans(segment.Text);
            var quotedSpans = MarkdownProseExtractor.FindQuotedOrEmphasisSpans(segment.Text);

            // Head-word spans of split phrasal verb findings already reported in this segment, so
            // a later (shorter) entry does not report the same head word again.
            var splitHeadSpans = new List<(int Start, int Length)>();
            var reportedSpans = new List<(int Start, int Length)>();

            foreach (var compiled in compiledEntries)
            {
                foreach (var hit in FindHits(compiled, segment.Text, dictionary, allowedTerms))
                {
                    if (hit.IsSplit
                        ? IntersectsAny(hit.Index, hit.Length, reportedSpans)
                        : IntersectsAny(hit.Index, hit.Length, splitHeadSpans))
                    {
                        continue;
                    }

                    if (MarkdownProseExtractor.OverlapsInlineCodeSpan(hit.Index, hit.Length, codeSpans))
                    {
                        continue;
                    }

                    if (MarkdownProseExtractor.OverlapsInlineCodeSpan(hit.Index, hit.Length, phraseSpans))
                    {
                        continue;
                    }

                    if (MarkdownProseExtractor.OverlapsInlineCodeSpan(hit.Index, hit.Length, admonitionSpans))
                    {
                        // A bold admonition label at the start of a block (for example
                        // "**Caution.**") is a label, not a prose sentence, so it is not run
                        // through the dictionary check.
                        continue;
                    }

                    if (MarkdownProseExtractor.OverlapsInlineCodeSpan(hit.Index, hit.Length, quotedSpans))
                    {
                        // A word inside a quotation or cited title (for example a document title
                        // in quotes or italics) is a mention of that exact text, not a use of the
                        // word in this document's own prose, so it is not flagged.
                        continue;
                    }

                    var diagnostic = BuildDiagnostic(file, segment, compiled, hit, resolver, codeSpans, collectDetail);
                    if (diagnostic is not null)
                    {
                        diagnostics.Add(diagnostic);
                        reportedSpans.Add((hit.Index, hit.Length));
                        if (hit.IsSplit)
                        {
                            splitHeadSpans.Add((hit.Index, hit.HeadLength));
                        }
                    }
                }
            }
        }

        return diagnostics;
    }

    /// <summary>
    ///     One generated word form of a dictionary entry: the sense that produced it and the
    ///     grammatical form(s) the spelling represents.
    /// </summary>
    /// <param name="Sense">The noun or verb sense the spelling was generated from.</param>
    /// <param name="Forms">The grammatical form(s) the spelling represents for that sense.</param>
    private sealed record FormOrigin(DictionarySense Sense, WordForm Forms);

    /// <summary>
    ///     An entry together with its once-per-call alternation pattern and generated spellings.
    /// </summary>
    /// <param name="Entry">The dictionary entry.</param>
    /// <param name="Pattern">Alternation matching the base term and every generated spelling.</param>
    /// <param name="Forms">
    ///     Generated spellings (lower case, single spaces) to their origins; the base term is
    ///     never a key.
    /// </param>
    /// <param name="SplitPattern">
    ///     Pattern for a phrasal verb split by other words, or <see langword="null"/> when the entry has none.
    /// </param>
    private sealed record CompiledEntry(
        DictionaryEntry Entry,
        Regex Pattern,
        IReadOnlyDictionary<string, List<FormOrigin>> Forms,
        Regex? SplitPattern);

    /// <summary>
    ///     One matched occurrence of an entry: a contiguous match of the base term or a generated
    ///     spelling (optionally with an allowed hyphen prefix), or a split phrasal verb.
    /// </summary>
    /// <param name="Index">Start of the flagged text within the segment.</param>
    /// <param name="Length">Length of the flagged text.</param>
    /// <param name="Value">The flagged text exactly as written.</param>
    /// <param name="Key">The matched spelling without prefix or gap (lower case, single spaces).</param>
    /// <param name="PrefixLength">Length of the hyphen prefix including the hyphen, or zero.</param>
    /// <param name="IsSplit">Whether the match is a phrasal verb split by other words.</param>
    /// <param name="HeadLength">For a split match, the length of the head word.</param>
    private sealed record Hit(int Index, int Length, string Value, string Key, int PrefixLength, bool IsSplit, int HeadLength);

    /// <summary>
    ///     Auxiliary and modal words (lower case) whose presence in a heading or table cell shows
    ///     that a participial form is part of a clause. Used by the fragment guard.
    /// </summary>
    private static readonly FrozenSet<string> AuxiliaryWords = new[]
    {
        "am", "is", "are", "was", "were", "be", "been", "being",
        "has", "have", "had", "having",
        "get", "gets", "got", "gotten", "getting",
        "can", "could", "shall", "should", "will", "would", "may", "might", "must"
    }.ToFrozenSet(StringComparer.OrdinalIgnoreCase);

    /// <summary>
    ///     Words that may not appear between the verb and the particle of a split phrasal verb:
    ///     prepositions, conjunctions and relative words (which start a new phrase or clause) and
    ///     the auxiliary words.
    /// </summary>
    private static readonly string[] SplitGapStopWords =
    [
        "to", "of", "in", "on", "at", "by", "with", "for", "from", "as", "and", "or", "but",
        "that", "which", "when", "if", "because", "than",
        "am", "is", "are", "was", "were", "be", "been", "being",
        "has", "have", "had", "having",
        "get", "gets", "got", "gotten", "getting",
        "can", "could", "shall", "should", "will", "would", "may", "might", "must"
    ];

    /// <summary>A word of letters, used to find auxiliary words.</summary>
    private static readonly Regex WordRegex = new(@"[A-Za-z]+", RegexOptions.CultureInvariant, TimeSpan.FromSeconds(1));

    /// <summary>
    ///     A sense plus the alternatives to show for it, already inflected where that was safe.
    /// </summary>
    /// <param name="Sense">The matching dictionary sense.</param>
    /// <param name="Alternatives">The alternatives to show (inflected, or base where not safe).</param>
    /// <param name="UsesBaseFallback">Whether any alternative fell back to its base form.</param>
    /// <param name="Safe">
    ///     For each alternative, whether it was inflected safely to the flagged form (always
    ///     <see langword="true"/> for a base-term match, which needs no inflection).
    /// </param>
    private sealed record Candidate(
        DictionarySense Sense,
        IReadOnlyList<string> Alternatives,
        bool UsesBaseFallback,
        IReadOnlyList<bool> Safe);

    /// <summary>
    ///     Compiles one alternation pattern per entry and builds its generated word-form map.
    /// </summary>
    /// <remarks>
    ///     Precedence for a generated spelling: it is dropped when it is itself an explicit
    ///     dictionary key, when it is allowed (per-file extra allowance, or the global allow and
    ///     ignore lists), or when an earlier (longer-term) entry already generated it.
    /// </remarks>
    private static List<CompiledEntry> CompileEntries(
        List<DictionaryEntry> entries,
        LintDictionary dictionary,
        HashSet<string>? allowedTerms)
    {
        var claimed = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var compiled = new List<CompiledEntry>(entries.Count);
        foreach (var entry in entries)
        {
            var forms = dictionary.MatchWordForms
                ? BuildFormMap(entry, dictionary, allowedTerms, claimed)
                : new Dictionary<string, List<FormOrigin>>();
            claimed.UnionWith(forms.Keys);

            var spellings = forms.Keys.Prepend(entry.Term).OrderByDescending(s => s.Length).ToList();
            var verbSense = entry.Senses.Any(s => s.Pos == PartOfSpeech.Verb);
            var allowsPrefix = dictionary.MatchWordForms
                                && verbSense
                                && entry.Term.All(c => char.ToLowerInvariant(c) is >= 'a' and <= 'z');
            var prefixGroup = allowsPrefix
                ? $"(?:(?<prefix>(?:{string.Join("|", WordFormInflector.HyphenPrefixes)})-))?"
                : string.Empty;
            var pattern = $@"(?<![\w-]){prefixGroup}(?<form>{string.Join("|", spellings.Select(SpellingToPattern))})(?![\w-])";
            compiled.Add(new CompiledEntry(
                entry,
                new Regex(pattern, RegexOptions.IgnoreCase | RegexOptions.CultureInvariant, TimeSpan.FromSeconds(1)),
                forms,
                dictionary.MatchWordForms ? BuildSplitPattern(entry, forms) : null));
        }

        return compiled;
    }

    /// <summary>
    ///     Builds the pattern for a phrasal verb split by one to three other words ("carry the test
    ///     out"), or <see langword="null"/> when the entry has no phrasal verb sense.
    /// </summary>
    private static Regex? BuildSplitPattern(DictionaryEntry entry, Dictionary<string, List<FormOrigin>> forms)
    {
        if (!entry.Senses.Any(s => WordFormInflector.IsPhrasalVerb(entry.Term, s.Pos)))
        {
            return null;
        }

        var words = entry.Term.Split(' ', StringSplitOptions.RemoveEmptyEntries);
        var heads = forms.Keys
            .Select(f => f.Split(' ')[0])
            .Prepend(words[0])
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderByDescending(h => h.Length)
            .Select(Regex.Escape);
        var stop = string.Join("|", SplitGapStopWords);
        var gapWord = $@"\s+(?!(?:{stop})(?![\w'’-]))[\w'’-]+";
        var pattern = $@"(?<![\w-])(?<head>{string.Join("|", heads)})(?:{gapWord}){{1,3}}\s+(?<particle>{Regex.Escape(words[1])})(?![\w-])";
        return new Regex(pattern, RegexOptions.IgnoreCase | RegexOptions.CultureInvariant, TimeSpan.FromSeconds(1));
    }

    /// <summary>
    ///     Finds every occurrence of an entry in a segment: contiguous matches (with an allowed hyphen
    ///     prefix where one applies) followed by split phrasal verb matches.
    /// </summary>
    private static IEnumerable<Hit> FindHits(
        CompiledEntry compiled,
        string text,
        LintDictionary dictionary,
        HashSet<string>? allowedTerms)
    {
        foreach (Match match in compiled.Pattern.Matches(text))
        {
            var form = match.Groups["form"];
            var key = string.Join(' ', form.Value.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries));
            var prefix = match.Groups["prefix"];
            if (!prefix.Success)
            {
                yield return new Hit(match.Index, match.Length, match.Value, key, 0, false, 0);
                continue;
            }

            // A prefixed spelling that is itself an explicit entry, or allowed, is not a form of
            // this entry (mirrors the precedence of generated spellings).
            var whole = (prefix.Value + key).ToLowerInvariant();
            if (dictionary.TryGetEntry(whole, out _)
                || dictionary.IsAllowedSpelling(whole)
                || (allowedTerms?.Contains(whole) ?? false))
            {
                continue;
            }

            yield return new Hit(match.Index, match.Length, match.Value, key, prefix.Length, false, 0);
        }

        if (compiled.SplitPattern is null)
        {
            yield break;
        }

        foreach (Match match in compiled.SplitPattern.Matches(text))
        {
            var head = match.Groups["head"].Value;
            var key = $"{head} {match.Groups["particle"].Value}";
            yield return new Hit(match.Index, match.Length, match.Value, key, 0, true, head.Length);
        }
    }

    /// <summary>
    ///     Generates the allowed-to-match inflected spellings of one entry, merged by spelling.
    /// </summary>
    private static Dictionary<string, List<FormOrigin>> BuildFormMap(
        DictionaryEntry entry,
        LintDictionary dictionary,
        HashSet<string>? allowedTerms,
        HashSet<string> claimed)
    {
        var forms = new Dictionary<string, List<FormOrigin>>(StringComparer.OrdinalIgnoreCase);
        foreach (var sense in entry.Senses)
        {
            foreach (var (spelling, form) in WordFormInflector.Generate(entry.Term, sense.Pos))
            {
                if (dictionary.TryGetEntry(spelling, out _)
                    || dictionary.IsAllowedSpelling(spelling)
                    || (allowedTerms?.Contains(spelling) ?? false)
                    || claimed.Contains(spelling))
                {
                    continue;
                }

                if (!forms.TryGetValue(spelling, out var origins))
                {
                    origins = [];
                    forms[spelling] = origins;
                }

                origins.Add(new FormOrigin(sense, form));
            }
        }

        return forms;
    }

    /// <summary>
    ///     Converts a literal word or phrase into a regex fragment with whitespace-tolerant spaces.
    /// </summary>
    private static string SpellingToPattern(string spelling)
    {
        return Regex.Escape(spelling).Replace(@"\ ", @"\s+", StringComparison.Ordinal);
    }

    /// <summary>
    ///     Compiles the allowed-phrase patterns once per call.
    /// </summary>
    private static List<Regex> CompilePhrasePatterns(IReadOnlyCollection<string>? allowedPhrases)
    {
        return (allowedPhrases ?? [])
            .Select(p => new Regex(
                $@"(?<![\w-]){SpellingToPattern(p)}(?![\w-])",
                RegexOptions.IgnoreCase,
                TimeSpan.FromSeconds(1)))
            .ToList();
    }

    /// <summary>
    ///     Locates every occurrence of every allowed phrase within
    ///     <paramref name="segmentText"/>, using the same case-insensitive, whitespace-tolerant
    ///     matching as a multi-word <see cref="DictionaryConfig.Disallow"/> term, so
    ///     callers can test whether a dictionary-term match falls entirely inside an approved
    ///     phrase (see <see cref="DictionaryConfig.AllowInPhrase"/>).
    /// </summary>
    private static List<(int Start, int Length)> FindAllowedPhraseSpans(
        string segmentText,
        List<Regex> phrasePatterns)
    {
        var spans = new List<(int Start, int Length)>();
        foreach (var pattern in phrasePatterns)
        {
            foreach (Match match in pattern.Matches(segmentText))
            {
                spans.Add((match.Index, match.Length));
            }
        }

        return spans;
    }

    /// <summary>
    ///     Builds the diagnostic for one matched occurrence, selecting the applicable sense(s) and
    ///     the corresponding confident-or-ambiguous message/suggestion wording, or
    ///     <see langword="null"/> when a confident resolution rules out every sense (the term is not
    ///     disallowed in the grammatical role it is being used in here).
    /// </summary>
    private static Diagnostic? BuildDiagnostic(
        string file,
        ProseSegment segment,
        CompiledEntry compiled,
        Hit hit,
        IPartOfSpeechResolver resolver,
        IReadOnlyList<(int Start, int Length)> codeSpans,
        bool collectDetail)
    {
        var entry = compiled.Entry;
        var origins = FindOrigins(compiled, hit.Key);
        if (hit.PrefixLength > 0 && origins is not null)
        {
            // A prefixed (hyphenated) form is only ever a form of a verb sense.
            origins = origins.Where(o => o.Sense.Pos == PartOfSpeech.Verb).ToList();
            if (origins.Count == 0)
            {
                return null;
            }
        }

        // The role is resolved on one token: the head word of a split or phrasal participial form
        // (the resolver does not resolve a multi-token span), or the stem of a hyphenated form
        // (the tagger does not know a prefixed word, so the prefix is left out of the sentence it
        // sees, which keeps every character offset after the prefix valid).
        var resolveText = segment.Text;
        var spanIndex = hit.Index;
        var spanLength = hit.Length;
        if (hit.IsSplit)
        {
            spanLength = hit.HeadLength;
        }
        else if (hit.PrefixLength > 0)
        {
            resolveText = resolveText.Remove(hit.Index, hit.PrefixLength);
            spanLength = hit.Length - hit.PrefixLength;
        }
        else if (origins is not null && origins.Any(o => WordFormInflector.IsParticipial(o.Forms)))
        {
            var headLength = hit.Value.IndexOfAny([' ', '\t', '\r', '\n']);
            if (headLength > 0)
            {
                spanLength = headLength;
            }
        }

        var roleEvidence = resolver.ResolveWithEvidence(resolveText, spanIndex, spanLength);
        var role = roleEvidence.Role;

        var fragmentApplies = origins is not null
            && segment.Role is SegmentRole.Heading or SegmentRole.TableRow
            && origins.All(o => WordFormInflector.IsParticipial(o.Forms));
        if (fragmentApplies && !HasAuxiliary(segment.Text, codeSpans))
        {
            // Fragment guard: a participial form in a heading or table cell with no auxiliary word
            // is a label ("Terminated", "Producing reports"), not a verb in a clause.
            return null;
        }

        // The base term keeps the original sense selection (including any-role senses); a
        // generated form is strict: only the noun/verb sense that generated it can apply.
        var candidates = origins is null
            ? BaseCandidates(entry, role, hit.PrefixLength > 0)
            : InflectedCandidates(origins, role, hit.IsSplit);

        if (origins is not null && candidates.Count == 0)
        {
            // Every generated-form origin was ruled out: either the role is confidently another
            // part of speech, or the role is unresolved and only participial origins existed
            // (an -ed/-ing or irregular past/participle form is flagged only when confidently
            // a verb).
            return null;
        }

        if (role is not null && candidates.Count == 0)
        {
            // The resolver confidently resolved a grammatical role that none of the entry's
            // senses restrict (for example, a verb-only entry matched where the term is used
            // as a noun): the word is not being used in a role ASD-STE100 disallows here, so no
            // diagnostic is reported.
            return null;
        }

        if (role is PartOfSpeech.Adjective or PartOfSpeech.Adverb
            && candidates.All(c => IsPureSelfReferentialSense(c.Sense, entry.Term)))
        {
            // A confident role can match several approved/no-replacement senses, including an
            // Any sense. Suppress the finding because none of the matching senses offers an
            // actionable replacement; unrelated senses are deliberately not considered.
            return null;
        }

        if (IsUnactionable(entry))
        {
            // Every sense's alternatives list includes its own headword (possibly alongside other
            // alternatives), and the senses between them cover more than one part of speech (for
            // example "support (n) -> SUPPORT, HOLD" and "support (v) -> HOLD, SUPPORT"). ASD-STE100
            // approves this word in every role it can grammatically take, so there is no
            // part-of-speech switch left that would resolve the finding - the resolver being right
            // or wrong changes nothing. This is a pure dictionary-shape test and does not depend on
            // the resolver at all.
            return null;
        }

        if (role is null && entry.Senses.Count == 1 && IsSelfReferential(entry))
        {
            // A self-referential entry (its alternatives list includes its own headword) is
            // ASD-STE100's convention for "this word is approved, but only in the other part of
            // speech" (for example "test (v) -> TEST", meaning the noun "test" is fine). When the
            // resolver could not confidently resolve a role at all, an inconclusive match against a
            // self-referential, single-sense entry is more likely a missed noun-compound/other
            // signal than a genuine disallowed usage, so it is not reported. This is deliberately
            // restricted to single-sense entries: a multi-sense entry that happens to include its
            // own headword among one sense's alternatives may still have a genuinely ambiguous
            // finding worth reporting under its other sense(s), so it is not suppressed here. A
            // confident resolution of the disallowed part of speech is still reported (handled by the
            // candidates check above); this only relaxes the previously-ambiguous case.
            return null;
        }

        var term = entry.Term;
        var formNote = origins is null ? string.Empty : $" (a form of '{term}')";
        if (hit.IsSplit)
        {
            formNote = $" (a split form of '{term}')";
        }
        else if (hit.PrefixLength > 0)
        {
            formNote = $" (a prefixed form of '{term}')";
        }
        var diagnostic = candidates.Count == 1
            ? ConfidentDiagnostic(file, segment, hit, entry.Term, candidates[0], entry.Senses.Count > 1, formNote)
            : AmbiguousDiagnostic(file, segment, hit, entry.Term, candidates, formNote);
        if (!collectDetail)
        {
            return diagnostic;
        }

        var participleRule = origins is not null
            && role == PartOfSpeech.Verb
            && origins.Any(o => WordFormInflector.IsParticipial(o.Forms))
                ? FindingDetail.RuleKeptConfidentVerb
                : FindingDetail.RuleNotApplicable;
        var evidence = new DictionaryEvidence(
            segment,
            hit.Index,
            hit.Length,
            hit.Value,
            entry.Term,
            FormKindsOf(origins),
            hit.IsSplit,
            hit.PrefixLength > 0,
            origins is not null,
            entry.Senses.Select(s => new EvidenceSense(PosLabel(s.Pos), s.Alternatives)).ToList(),
            candidates.Count == 1 ? PosLabel(candidates[0].Sense.Pos) : FindingDetail.SensePosAmbiguous,
            candidates.Count,
            DetailSuggestions(candidates, entry.Term, hit.Value),
            roleEvidence,
            participleRule,
            fragmentApplies ? FindingDetail.RuleKeptAuxiliaryPresent : FindingDetail.RuleNotApplicable);
        return diagnostic with { Evidence = evidence };
    }

    /// <summary>
    ///     Names the grammatical forms a matched spelling represents, or <c>base</c> for the base term.
    /// </summary>
    private static IReadOnlyList<string> FormKindsOf(List<FormOrigin>? origins)
    {
        if (origins is null)
        {
            return [FindingDetail.FormBase];
        }

        var forms = origins.Aggregate(WordForm.None, (all, o) => all | o.Forms);
        var kinds = new List<string>();
        if (forms.HasFlag(WordForm.ThirdPersonSingular))
        {
            kinds.Add("third-person");
        }

        if (forms.HasFlag(WordForm.Past))
        {
            kinds.Add("past");
        }

        if (forms.HasFlag(WordForm.PastParticiple))
        {
            kinds.Add("participle");
        }

        if (forms.HasFlag(WordForm.Gerund))
        {
            kinds.Add("gerund");
        }

        if (forms.HasFlag(WordForm.Plural))
        {
            kinds.Add("plural");
        }

        return kinds;
    }

    /// <summary>
    ///     Lists the suggested alternatives of every candidate sense with their inflection-safe flag,
    ///     using the same filtering as the diagnostic's suggestion text.
    /// </summary>
    private static List<EvidenceSuggestion> DetailSuggestions(
        IReadOnlyList<Candidate> candidates,
        string term,
        string matchedWord)
    {
        var suggestions = new List<EvidenceSuggestion>();
        foreach (var candidate in candidates.Where(c => !IsPureSelfReferentialSense(c.Sense, term)))
        {
            for (var i = 0; i < candidate.Alternatives.Count; i++)
            {
                if (!string.Equals(candidate.Alternatives[i], matchedWord, StringComparison.OrdinalIgnoreCase))
                {
                    suggestions.Add(new EvidenceSuggestion(
                        candidate.Alternatives[i],
                        candidate.Safe[i],
                        PosLabel(candidate.Sense.Pos)));
                }
            }
        }

        return suggestions;
    }

    /// <summary>
    ///     Returns the generated-form origins when the matched spelling is an inflected spelling, or
    ///     <see langword="null"/> when it is the base term.
    /// </summary>
    private static List<FormOrigin>? FindOrigins(CompiledEntry compiled, string key)
    {
        if (compiled.Forms.Count == 0)
        {
            return null;
        }

        return compiled.Forms.TryGetValue(key, out var origins) ? origins : null;
    }

    /// <summary>
    ///     Determines whether a segment contains an auxiliary or modal word outside its inline code
    ///     spans (see <see cref="AuxiliaryWords"/>); such a word shows that a participial form is
    ///     part of a clause rather than a bare label.
    /// </summary>
    private static bool HasAuxiliary(string text, IReadOnlyList<(int Start, int Length)> codeSpans)
    {
        return WordRegex.Matches(text).Any(word =>
            AuxiliaryWords.Contains(word.Value)
            && !MarkdownProseExtractor.OverlapsInlineCodeSpan(word.Index, word.Length, codeSpans));
    }

    /// <summary>
    ///     Determines whether a span intersects any span in a list (any shared character).
    /// </summary>
    private static bool IntersectsAny(int start, int length, List<(int Start, int Length)> spans)
    {
        var end = start + length;
        return spans.Any(s => start < s.Start + s.Length && s.Start < end);
    }

    /// <summary>
    ///     Selects the senses that apply to a match of the base term, unchanged from the
    ///     pre-word-form behavior: any resolved role keeps matching and any-role senses. A
    ///     prefixed (hyphenated) match is restricted to verb senses.
    /// </summary>
    private static List<Candidate> BaseCandidates(DictionaryEntry entry, PartOfSpeech? role, bool verbOnly)
    {
        var senses = role is null
            ? entry.Senses
            : entry.Senses.Where(s => s.Pos == role || s.Pos == PartOfSpeech.Any).ToList();
        if (verbOnly)
        {
            senses = senses.Where(s => s.Pos == PartOfSpeech.Verb).ToList();
        }

        return senses.Select(s => new Candidate(s, s.Alternatives, false, s.Alternatives.Select(_ => true).ToList())).ToList();
    }

    /// <summary>
    ///     Selects the senses that apply to a match of a generated word form: strictly the senses
    ///     whose part of speech equals the resolved role. When the role is unknown, participial
    ///     origins (-ed, -ing, past, past participle) are dropped and the remaining origins are kept.
    ///     Each candidate has its alternatives inflected to the flagged form where that is safe; a
    ///     split phrasal match never inflects a phrasal alternative, because the alternative cannot
    ///     be split around the same words.
    /// </summary>
    private static List<Candidate> InflectedCandidates(List<FormOrigin> origins, PartOfSpeech? role, bool split)
    {
        var candidates = new List<Candidate>();
        foreach (var origin in origins.Where(o => role is null
            ? !WordFormInflector.IsParticipial(o.Forms)
            : o.Sense.Pos == role))
        {
            var alternatives = new List<string>();
            var safe = new List<bool>();
            var fallback = false;
            foreach (var alternative in origin.Sense.Alternatives)
            {
                var inflected = split && alternative.Contains(' ')
                    ? null
                    : WordFormInflector.Inflect(alternative, origin.Forms, origin.Sense.Pos);
                fallback |= inflected is null;
                alternatives.Add(inflected ?? alternative);
                safe.Add(inflected is not null);
            }

            candidates.Add(new Candidate(origin.Sense, alternatives, fallback, safe));
        }

        return candidates;
    }

    /// <summary>
    ///     Determines whether an entry is "self-referential": at least one sense's
    ///     <see cref="DictionarySense.Alternatives"/> list includes the entry's own headword
    ///     (case-insensitive). This is ASD-STE100's convention for a dual-role word where the
    ///     correction is a change of grammatical role rather than a different word (for example
    ///     <c>test (v) -&gt; TEST</c>, meaning the noun "test" is the approved form).
    /// </summary>
    private static bool IsSelfReferential(DictionaryEntry entry)
    {
        return entry.Senses.Any(s => IsSelfReferentialSense(s, entry.Term));
    }

    /// <summary>
    ///     Determines whether every sense of an entry is "unactionable": every sense's
    ///     <see cref="DictionarySense.Alternatives"/> list includes the entry's own headword
    ///     (case-insensitive; other alternatives may also be listed), and the entry's senses
    ///     collectively cover more than one part of speech. For example <c>support (n) -&gt; SUPPORT,
    ///     HOLD</c> combined with <c>support (v) -&gt; HOLD, SUPPORT</c> approves "support" in every
    ///     role it can grammatically take, so there is no part-of-speech switch that would resolve
    ///     a finding: whichever role the word is used in here, ASD-STE100 already approves it in
    ///     that role. Such an entry can never produce an actionable diagnostic and is never
    ///     flagged, regardless of what <see cref="IPartOfSpeechResolver.Resolve"/> returns. This differs
    ///     from <see cref="IsSelfReferential"/> only in scope: <see cref="IsSelfReferential"/> asks
    ///     whether *any* sense is self-referential (used to relax a single-sense entry's
    ///     inconclusive-resolution case), whereas this asks whether *every* sense across *more than one*
    ///     part of speech is self-referential (used to suppress the finding outright, independent of
    ///     the resolver).
    /// </summary>
    private static bool IsUnactionable(DictionaryEntry entry)
    {
        if (entry.Senses.Count < 2)
        {
            return false;
        }

        var distinctPos = entry.Senses.Select(s => s.Pos).Distinct().Count();
        if (distinctPos < 2)
        {
            return false;
        }

        return entry.Senses.All(s => IsSelfReferentialSense(s, entry.Term));
    }

    /// <summary>
    ///     Determines whether a single sense's <see cref="DictionarySense.Alternatives"/> list
    ///     includes the entry's own headword (case-insensitive).
    /// </summary>
    private static bool IsSelfReferentialSense(DictionarySense sense, string term)
    {
        return sense.Alternatives.Any(a => string.Equals(a, term, StringComparison.OrdinalIgnoreCase));
    }

    /// <summary>
    ///     Determines whether a sense is "purely" self-referential: its <em>only</em> alternative
    ///     is the entry's own headword, with no other genuine replacement word offered (for example
    ///     <c>test (v) -&gt; TEST</c>). For such a sense, "avoid X; use X instead" would be a
    ///     nonsensical no-op message, since there is no actual word swap to make - the real
    ///     correction is a change of grammatical role. This is distinct from a sense whose
    ///     alternatives include the headword <em>alongside</em> other real alternatives (for
    ///     example <c>check (v) -&gt; MAKE SURE, MEASURE, EXAMINE, CHECK</c>), which already reads as
    ///     an actionable message and is left untouched.
    /// </summary>
    private static bool IsPureSelfReferentialSense(DictionarySense sense, string term)
    {
        return sense.Alternatives.Count == 1 && IsSelfReferentialSense(sense, term);
    }

    /// <summary>
    ///     Builds a diagnostic for a confidently-resolved sense (either the sole sense of a
    ///     single-sense term, or the single surviving candidate of a multi-sense term).
    /// </summary>
    private static Diagnostic ConfidentDiagnostic(
        string file,
        ProseSegment segment,
        Hit hit,
        string term,
        Candidate candidate,
        bool labelPos,
        string formNote)
    {
        var sense = candidate.Sense;
        if (IsPureSelfReferentialSense(sense, term))
        {
            // "Avoid 'test'; use 'TEST' instead" is a nonsensical no-op wording, since the only
            // "alternative" is the same word. The real, actionable correction is a change of
            // grammatical role, not a word swap, so the message is phrased accordingly and no
            // word-substitution suggestion is offered.
            return new Diagnostic(
                file,
                segment.ResolveLine(hit.Index),
                null,
                RuleCodes.Dictionary,
                Severity.Error,
                $"Avoid using '{hit.Value}' as a {PosLabel(sense.Pos)}; ASD-STE100 approves " +
                $"'{term}' only in a different grammatical role.",
                $"Rewrite the sentence so '{term}' is not used as a {PosLabel(sense.Pos)}.");
        }

        var alternatives = FilterSelfAlternatives(candidate.Alternatives, hit.Value);

        string message;
        if (alternatives.Count > 0)
        {
            message = labelPos
                ? $"Avoid '{hit.Value}'{formNote}; use {JoinAlternatives(alternatives)} instead (used as a {PosLabel(sense.Pos)})."
                : $"Avoid '{hit.Value}'{formNote}; use {JoinAlternatives(alternatives)} instead.";
            if (candidate.UsesBaseFallback)
            {
                message += BaseFallbackNote;
            }
        }
        else
        {
            message = labelPos
                ? $"Avoid '{hit.Value}'{formNote}; it is not an approved ASD-STE100-style term (used as a {PosLabel(sense.Pos)})."
                : $"Avoid '{hit.Value}'{formNote}; it is not an approved ASD-STE100-style term.";
        }

        // Citations always cite the dictionary's own (base-form) alternatives.
        var citations = FilterSelfAlternatives(sense.Alternatives, hit.Value);
        return new Diagnostic(
            file,
            segment.ResolveLine(hit.Index),
            null,
            RuleCodes.Dictionary,
            Severity.Error,
            message,
            alternatives.Count > 0 ? string.Join(", ", alternatives) : null,
            alternatives.Count > 0
                ? citations.Select(a => new DictionaryCitation(a, PosLabel(sense.Pos))).ToList()
                : null);
    }

    /// <summary>
    ///     Sentence appended to a message when at least one suggested alternative could not be
    ///     inflected safely and is therefore shown in its base form.
    /// </summary>
    private const string BaseFallbackNote = " The alternative is shown in its base form; adjust it to fit the sentence.";

    /// <summary>
    ///     Removes the flagged match's own text (case-insensitive) from a sense's
    ///     <see cref="DictionarySense.Alternatives"/> list before it is used to build a
    ///     suggestion/citation, since suggesting the exact word just flagged as its own
    ///     "alternative" is a no-op that would confuse rather than help the reader. Distinct from
    ///     <see cref="IsSelfReferentialSense"/>/<see cref="IsPureSelfReferentialSense"/>, which
    ///     compare against the dictionary entry's own headword (<see cref="DictionaryEntry.Term"/>)
    ///     for role-restriction detection and are unaffected by this filtering: the matched surface
    ///     form (for example an inflected "running") can differ from the entry's headword
    ///     (for example "run"), so both comparisons are needed and neither replaces the other.
    /// </summary>
    private static IReadOnlyList<string> FilterSelfAlternatives(IReadOnlyList<string> alternatives, string matchedWord)
    {
        return alternatives
            .Where(a => !string.Equals(a, matchedWord, StringComparison.OrdinalIgnoreCase))
            .ToList();
    }

    /// <summary>
    ///     Builds a diagnostic listing every candidate sense for a term whose grammatical role
    ///     could not be confidently resolved.
    /// </summary>
    private static Diagnostic AmbiguousDiagnostic(
        string file,
        ProseSegment segment,
        Hit hit,
        string term,
        IReadOnlyList<Candidate> candidates,
        string formNote)
    {
        // A candidate whose only alternative is the entry's own headword (see
        // IsPureSelfReferentialSense) is phrased as a role restriction, not a word swap, for the
        // same reason as ConfidentDiagnostic - "use 'test'" is a nonsensical no-op when the term
        // being flagged already is "test". A candidate with no alternatives at all (disallowed in
        // that role with no suggested replacement word) is excluded from the suggestion the same
        // way, so it does not leave a stray leading-space/bare-part-of-speech fragment (for example
        // " (adjective)") in the combined string; its role restriction is still surfaced via
        // CorrectionClause in the message's "possible corrections" text. Citations keep the
        // dictionary's own base-form alternatives.
        var corrections = string.Join("; ", candidates.Select(c => CorrectionClause(c, term, hit.Value)));
        var citableCandidates = candidates
            .Select(c => (Candidate: c, Alternatives: FilterSelfAlternatives(c.Alternatives, hit.Value)))
            .Where(c => !IsPureSelfReferentialSense(c.Candidate.Sense, term) && c.Alternatives.Count > 0)
            .ToList();
        var suggestion = string.Join("; ", citableCandidates
            .Select(c => $"{string.Join(", ", c.Alternatives)} ({PosLabel(c.Candidate.Sense.Pos)})"));
        var citations = citableCandidates
            .SelectMany(c => FilterSelfAlternatives(c.Candidate.Sense.Alternatives, hit.Value)
                .Select(a => new DictionaryCitation(a, PosLabel(c.Candidate.Sense.Pos))))
            .ToList();

        var message = $"Ambiguous part of speech for '{hit.Value}'{formNote} \u2014 possible corrections: {corrections}.";
        if (candidates.Any(c => c.UsesBaseFallback && c.Alternatives.Count > 0))
        {
            message += BaseFallbackNote;
        }

        return new Diagnostic(
            file,
            segment.ResolveLine(hit.Index),
            null,
            RuleCodes.Dictionary,
            Severity.Error,
            message,
            suggestion.Length > 0 ? suggestion : null,
            citations.Count > 0 ? citations : null);
    }

    /// <summary>
    ///     Renders one candidate sense's clause for <see cref="AmbiguousDiagnostic"/>'s
    ///     "possible corrections" message, using role-restriction wording for a purely
    ///     self-referential sense (see <see cref="IsPureSelfReferentialSense"/>) instead of a
    ///     nonsensical "use 'X'" word-swap suggestion.
    /// </summary>
    private static string CorrectionClause(Candidate candidate, string term, string matchedWord)
    {
        var sense = candidate.Sense;
        if (IsPureSelfReferentialSense(sense, term))
        {
            return $"as a {PosLabel(sense.Pos)}, only a different grammatical role is approved";
        }

        var alternatives = FilterSelfAlternatives(candidate.Alternatives, matchedWord);
        return alternatives.Count > 0
            ? $"as a {PosLabel(sense.Pos)}, use {JoinAlternatives(alternatives)}"
            : $"as a {PosLabel(sense.Pos)}";
    }

    /// <summary>
    ///     Renders a <see cref="PartOfSpeech"/> value for diagnostic message/suggestion text,
    ///     rendering <see cref="PartOfSpeech.Any"/> as "general" to avoid the awkward
    ///     "used as a any" phrasing.
    /// </summary>
    private static string PosLabel(PartOfSpeech pos) => pos switch
    {
        PartOfSpeech.Any => "general",
        PartOfSpeech.Noun => "noun",
        PartOfSpeech.Verb => "verb",
        PartOfSpeech.Adjective => "adjective",
        PartOfSpeech.Adverb => "adverb",
        _ => pos.ToString().ToLowerInvariant()
    };

    /// <summary>
    ///     Joins a sense's alternatives into natural "or" phrasing for embedding in a diagnostic
    ///     <see cref="Diagnostic.Message"/>: a single alternative is quoted alone, two alternatives
    ///     are joined with "or" (no Oxford comma), and three or more are joined with commas plus an
    ///     Oxford comma before the final "or".
    /// </summary>
    private static string JoinAlternatives(IReadOnlyList<string> alternatives)
    {
        var quoted = alternatives.Select(a => $"'{a}'").ToList();
        return quoted.Count switch
        {
            0 => string.Empty,
            1 => quoted[0],
            2 => $"{quoted[0]} or {quoted[1]}",
            _ => string.Join(", ", quoted.Take(quoted.Count - 1)) + ", or " + quoted[^1]
        };
    }
